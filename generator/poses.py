def draw_pose(view='front', size=(1024,1536)):
    canvas = np.zeros((size[1], size[0], 3), dtype=np.uint8)
    points = [None if p is None else (round(p[0]*size[0]/1024), round(p[1]*size[1]/1536)) for p in POINTS[view]]
    for i, (a,b) in enumerate(LIMBS):
        if points[a] is not None and points[b] is not None:
            cv2.line(canvas, points[a], points[b], COLORS[i], 12)
    for i,p in enumerate(points):
        if p is not None:
            cv2.circle(canvas,p,10,COLORS[i],-1)
    return canvas
